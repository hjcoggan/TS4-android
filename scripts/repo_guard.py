"""Pre-commit guard: rejects staged files derived from the game (ADR-0006), and host code that
passes paths through the ANSI code page.

Run from .githooks/pre-commit. Checks the staged content, not the working tree.
"""

import re
import subprocess
import sys

# Disc and Title Update file types, and images unpacked from them.
FORBIDDEN_EXTENSIONS = {".xex", ".xexp", ".arc", ".bik", ".iso", ".bin", ".pe", ".xbe", ".xmv", ".xma", ".wmv"}
FORBIDDEN_DIRECTORIES = ("generated/", "gamedata/", "updatedata/", ".iso/", "analysis/xex/")
STFS_MAGICS = (b"CON ", b"LIVE", b"PIRS")
GENERATED_MARKERS = (b"// Generated by rexglue", b"# Auto-generated by rexglue")
# Binary files above this are refused whatever they are; source repos hold no such blobs.
MAX_BINARY_BYTES = 512 * 1024
SNIFF_BYTES = 8192
# Host code (src/, C++): path::string() and narrow fopen go through the ANSI code page, so a
# per-user path with a user name outside it throws or fails to open. Use u8string() for text and
# a wide open; a line ending in the marker is a known-ASCII or non-Windows use.
HOST_CODE = re.compile(r"^src/(?!thirdparty/).*\.(cpp|h|hpp)$")
NARROW_PATH = re.compile(r"\.string\(\)|(?<!\w)(?:std::)?fopen\(")
NARROW_PATH_OK = "// narrow path ok"


def git(*args):
    return subprocess.run(["git", *args], capture_output=True, check=True).stdout


def staged_paths():
    out = git("diff", "--cached", "--name-only", "-z", "--diff-filter=ACMR")
    return [p.decode() for p in out.split(b"\0") if p]


def head_of(path):
    with subprocess.Popen(["git", "cat-file", "blob", f":{path}"], stdout=subprocess.PIPE) as cat:
        head = cat.stdout.read(SNIFF_BYTES)
        cat.kill()
    return head


def path_reason(path):
    lower = path.lower()
    if lower.startswith(FORBIDDEN_DIRECTORIES):
        return "in a generated or game data directory"
    dot = lower.rfind(".")
    if dot > lower.rfind("/") and lower[dot:] in FORBIDDEN_EXTENSIONS:
        return f"game file type ({lower[dot:]})"
    return None


def content_reason(size, head):
    if head.startswith(STFS_MAGICS):
        return "STFS package"
    if head.startswith(b"XEX2"):
        return "XEX image"
    if head.startswith(b"MZ"):
        return "PE image"
    if head.lstrip(b"\xef\xbb\xbf").startswith(GENERATED_MARKERS):
        return "generated by ReXGlue"
    if size > MAX_BINARY_BYTES and b"\0" in head:
        return f"large binary file ({size} bytes)"
    return None


def narrow_path_lines(path):
    """Lines of a staged host source file that pass a path through the ANSI code page."""
    if not HOST_CODE.match(path):
        return []
    text = git("cat-file", "blob", f":{path}").decode("utf-8", "replace")
    return [f"  {path}:{number}: {line.strip()}"
            for number, line in enumerate(text.splitlines(), 1)
            if NARROW_PATH.search(line) and not line.rstrip().endswith(NARROW_PATH_OK)]


def main():
    offenders, narrow = [], []
    for path in staged_paths():
        why = path_reason(path) or content_reason(int(git("cat-file", "-s", f":{path}")), head_of(path))
        if why:
            offenders.append(f"  {path}: {why}")
        else:
            narrow += narrow_path_lines(path)
    if offenders:
        print("Commit rejected: these files must not be in the repository (ADR-0006):", file=sys.stderr)
        print("\n".join(offenders), file=sys.stderr)
    if narrow:
        print("Commit rejected: these lines pass a path through the ANSI code page "
              "(path::string() or narrow fopen); use u8string() and a wide open, or end the line "
              f"with '{NARROW_PATH_OK}' for a known-ASCII or non-Windows use:", file=sys.stderr)
        print("\n".join(narrow), file=sys.stderr)
    return 1 if offenders or narrow else 0


if __name__ == "__main__":
    sys.exit(main())
