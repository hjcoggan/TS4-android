"""Write the launcher's disc and TU1 manifests from the owner's own copies.

Usage: python scripts/write_manifests.py --disc <iso> --tu-files <dir>

--disc reads the game partition of an Xbox 360 disc image without mounting it and writes
launcher/disc-manifest.tsv. --tu-files hashes the files unpacked from the TU1 package
(scripts/stfs_extract.py) and writes launcher/tu1-manifest.tsv. The manifests hold paths,
sizes and SHA-256s only, never game data (ADR-0006). Standard library only.
"""

import argparse
import hashlib
import struct
from pathlib import Path

MAGIC = b"MICROSOFT*XBOX*MEDIA"
# Where the game partition starts: plain XDVDFS, then the XGD2, XGD3 and XGD1 layouts.
PARTITIONS = (0, 0xFD90000, 0x2080000, 0x18300000)
SECTOR = 2048
TITLE_ID = 0x54540859
MEDIA_ID = 0x60819732
MODULES = ("default.xex", "Loader_DLL.xex", "Swing_DLL.xex")
PATCHES = ("default.xexp", "Loader_DLL.xexp", "Swing_DLL.xexp")
ROOT = Path(__file__).resolve().parent.parent


class Disc:
    def __init__(self, path):
        self.stream = Path(path).open("rb")
        self.size = Path(path).stat().st_size
        for base in PARTITIONS:
            if base + 0x10000 + SECTOR > self.size:
                continue
            header = self.read(base + 0x10000, SECTOR)
            if header[:20] == MAGIC and header[-20:] == MAGIC:
                self.base = base
                self.root = struct.unpack_from("<II", header, 20)
                return
        raise ValueError("No XDVDFS game partition found")

    def read(self, offset, size):
        if offset < 0 or offset + size > self.size:
            raise ValueError(f"Read outside the image: {offset}+{size}")
        self.stream.seek(offset)
        return self.stream.read(size)

    def files(self):
        result = []

        def directory(sector, size, parent, depth):
            if depth > 64:
                raise ValueError("Excessively deep directory structure")
            if size == 0:
                return
            data = self.read(self.base + sector * SECTOR, size)
            pending, seen = [0], set()
            while pending:
                offset = pending.pop()
                if offset in seen or offset + 14 > size:
                    raise ValueError("Invalid directory entry pointer")
                seen.add(offset)
                left, right, entry_sector, length, attributes, name_len = struct.unpack_from("<HHIIBB", data, offset)
                name = data[offset + 14:offset + 14 + name_len].decode("ascii")
                relative = f"{parent}/{name}" if parent else name
                if attributes & 0x10:
                    directory(entry_sector, length, relative, depth + 1)
                else:
                    result.append((relative, self.base + entry_sector * SECTOR, length))
                pending.extend(pointer * 4 for pointer in (right, left) if pointer)

        directory(*self.root, "", 0)
        return sorted(result, key=lambda entry: entry[0].lower())

    def sha256(self, offset, size):
        digest = hashlib.sha256()
        self.stream.seek(offset)
        while size:
            block = self.stream.read(min(1 << 20, size))
            if not block:
                raise ValueError("Truncated image")
            digest.update(block)
            size -= len(block)
        return digest.hexdigest()


def execution_info(xex):
    """(media ID, version, title ID) from an XEX2 header's execution info (key 0x00040006)."""
    if xex[:4] != b"XEX2":
        raise ValueError("Not an XEX2 image")
    count = struct.unpack_from(">I", xex, 20)[0]
    for index in range(count):
        key, value = struct.unpack_from(">II", xex, 24 + index * 8)
        if key == 0x00040006:
            media, version, _, title = struct.unpack_from(">IIII", xex, value)
            return media, version, title
    raise ValueError("No execution info")


def write(path, title, version, entries):
    lines = [f"# {title}: paths, sizes and SHA-256s, no game data.",
             "# Generated by scripts/write_manifests.py. The launcher verifies preparation against it.",
             f"manifest_version\t{version}"]
    lines += [f"{sha}\t{size}\t{name}" for name, size, sha in entries]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Wrote {path} ({len(entries)} files, {sum(size for _, size, _ in entries)} bytes)")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--disc", type=Path)
    parser.add_argument("--tu-files", type=Path)
    args = parser.parse_args()
    if args.disc:
        disc = Disc(args.disc)
        files = disc.files()
        print(f"Game partition at 0x{disc.base:X}, {len(files)} files")
        by_name = {name.lower(): (offset, size) for name, offset, size in files}
        for module in MODULES:
            offset, size = by_name[module.lower()]
            media, version, title = execution_info(disc.read(offset, min(size, 0x10000)))
            if (title, media, version) != (TITLE_ID, MEDIA_ID, 3):
                raise SystemExit(f"{module} is not the Reference build's disc module")
        entries = []
        for index, (name, offset, size) in enumerate(files, 1):
            entries.append((name, size, disc.sha256(offset, size)))
            print(f"[{index}/{len(files)}] {name}", flush=True)
        write(ROOT / "launcher/disc-manifest.tsv", "Top Spin 4 disc manifest (media 60819732)",
              "54540859-60819732-v0.0.0.3", entries)
    if args.tu_files:
        names = sorted((p for p in args.tu_files.rglob("*") if p.is_file()), key=lambda p: str(p).lower())
        if not {p.lower() for p in PATCHES} <= {p.name.lower() for p in names}:
            raise SystemExit("The TU1 folder lacks a module patch")
        entries = [(p.relative_to(args.tu_files).as_posix(), p.stat().st_size,
                    hashlib.sha256(p.read_bytes()).hexdigest()) for p in names]
        write(ROOT / "launcher/tu1-manifest.tsv", "Top Spin 4 Title Update 1 manifest (TU_1A5822P_000000C000000.0000000000083)",
              "54540859-60819732-tu1-v0.0.1.3", entries)


if __name__ == "__main__":
    main()
