"""The pre-commit guard (ADR-0006), exercised through real commits in a scratch repository."""

import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]


def git(repo, *args):
    return subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True)


@pytest.fixture
def repo(tmp_path):
    git(tmp_path, "init", "-q")
    git(tmp_path, "config", "user.name", "Test")
    git(tmp_path, "config", "user.email", "test@example.invalid")
    git(tmp_path, "config", "commit.gpgsign", "false")
    git(tmp_path, "config", "core.hooksPath", (ROOT / ".githooks").as_posix())
    return tmp_path


def commit(repo, name, content):
    path = repo / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(content if isinstance(content, bytes) else content.encode())
    git(repo, "add", "-f", name)
    return git(repo, "commit", "-q", "-m", f"Add {name}")


def test_source_file_commits(repo):
    result = commit(repo, "src/main.cpp", "int main() { return 0; }\n")
    assert result.returncode == 0, result.stderr


@pytest.mark.parametrize("name", [
    "default.xex", "Swing_DLL.xexp", "Core.arc", "2KLogoFootage.bik",
    "disc/Top Spin 4.iso", "Boot.bin", "analysis/swing.pe",
])
def test_game_file_extension_is_rejected(repo, name):
    result = commit(repo, name, "dummy\n")
    assert result.returncode != 0
    assert name in result.stderr


@pytest.mark.parametrize("magic", [b"CON ", b"LIVE", b"PIRS"])
def test_stfs_package_is_rejected(repo, magic):
    result = commit(repo, "TU_1A5822P_000000C000000.0000000000083", magic + b"\0" * 64)
    assert result.returncode != 0
    assert "STFS" in result.stderr


def test_xex_image_without_extension_is_rejected(repo):
    result = commit(repo, "blob", b"XEX2" + b"\0" * 64)
    assert result.returncode != 0


def test_pe_image_is_rejected(repo):
    result = commit(repo, "image.dat", b"MZ\x90\0" + b"\0" * 64)
    assert result.returncode != 0
    assert "PE" in result.stderr


def test_generated_source_is_rejected(repo):
    result = commit(repo, "src/swing_recomp.0.cpp", "// Generated by rexglue\n// DO NOT EDIT\n")
    assert result.returncode != 0
    assert "generated" in result.stderr


def test_generated_directory_is_rejected(repo):
    result = commit(repo, "generated/swing/sources.cmake", "set(X)\n")
    assert result.returncode != 0


def test_large_binary_is_rejected(repo):
    result = commit(repo, "assets/blob.dat", bytes(range(256)) * 4096)
    assert result.returncode != 0
    assert "large" in result.stderr


def test_large_text_file_commits(repo):
    result = commit(repo, "docs/notes.md", "A line of notes.\n" * 20000)
    assert result.returncode == 0, result.stderr


def test_rejected_commit_lists_every_offender(repo):
    (repo / "a.xex").write_text("x")
    (repo / "b.arc").write_text("x")
    git(repo, "add", "-f", "a.xex", "b.arc")
    result = git(repo, "commit", "-q", "-m", "Both")
    assert result.returncode != 0
    assert "a.xex" in result.stderr and "b.arc" in result.stderr


@pytest.mark.parametrize("line", [
    '  REXLOG_INFO("{}", path.string());',
    '  FILE* file = std::fopen(name.c_str(), "wb");',
    '  FILE* file = fopen(name, "wb");',
])
def test_host_code_with_a_narrow_path_is_rejected(repo, line):
    # path::string() and narrow fopen go through the ANSI code page: a per-user path with a
    # user name outside it throws or fails to open.
    result = commit(repo, "src/frame_dumps.cpp", f"void F() {{\n{line}\n}}\n")
    assert result.returncode != 0
    assert "src/frame_dumps.cpp:2" in result.stderr


def test_a_narrow_path_marked_ok_commits(repo):
    result = commit(repo, "src/frame_dumps.cpp",
                    'FILE* Open() { return std::fopen(path.c_str(), "w"); }  // narrow path ok\n')
    assert result.returncode == 0, result.stderr


def test_wide_paths_and_code_outside_src_commit(repo):
    assert commit(repo, "src/a.cpp", "auto f = _wfopen(path.c_str(), L\"w\");\nauto s = Utf8(path);\n").returncode == 0
    assert commit(repo, "scripts/tool.py", "print(path.string())\n").returncode == 0
